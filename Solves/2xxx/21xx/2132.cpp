class Solution
{
public:
    bool possibleToStamp(vector<vector<int>> &grid, int stampHeight, int stampWidth)
    {
        int n = grid.size();
        int m = grid[0].size();
        cout << n << " " << m << endl;
        vector<vector<int>> prefix(n + 1, vector<int>(m + 1, 0));
        vector<vector<int>> canPut(n + 1, vector<int>(m + 1, 0));
        for (int i = 1; i <= n; ++i)
        {
            for (int j = 1; j <= m; ++j)
            {
                prefix[i][j] = prefix[i][j - 1] + prefix[i - 1][j] - prefix[i - 1][j - 1] + grid[i - 1][j - 1];
            }
        }

        for (int i = 1; i <= n; ++i)
        {
            for (int j = 1; j <= m; ++j)
            {
                if (i + stampHeight - 1 <= n && j + stampWidth - 1 <= m)
                {
                    int queryPrefix = prefix[i + stampHeight - 1][j + stampWidth - 1] - prefix[i + stampHeight - 1][j - 1] - prefix[i - 1][j + stampWidth - 1] + prefix[i - 1][j - 1];
                    if (queryPrefix == 0)
                    {
                        canPut[i][j] = 1;
                    }
                }

                canPut[i][j] += canPut[i][j - 1] + canPut[i - 1][j] - canPut[i - 1][j - 1];

                int totalPutted = canPut[i][j];
                if (i >= stampHeight)
                {
                    totalPutted -= canPut[i - stampHeight][j];
                }

                if (j > stampWidth)
                {
                    totalPutted -= canPut[i][j - stampWidth];
                }

                if (i >= stampHeight && j >= stampWidth)
                {
                    totalPutted += canPut[i - stampHeight][j - stampWidth];
                }

                if (grid[i - 1][j - 1] == 0 && totalPutted == 0)
                {
                    cout << "false at cell (" << i << ", " << j << ")" << endl;
                    return false;
                }
            }
        }
        return true;
    }
};

